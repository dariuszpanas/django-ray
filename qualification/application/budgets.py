"""Explicit wall-clock accounting for sequential work on the owned capacity."""

FIRST_SECONDS = 180
EXISTING_SECONDS = 600
RQ2_SECONDS = 180
SHOWCASE_SECONDS = 180
PROTOCOL_SECONDS = 120
SURFACE_SECONDS = 30

# Preserve the repaired core plus rq2 allowance; the three added generation
# phases consume an increased wall-clock cap, not unused existing time.
BASE_APPLICATION_SECONDS = 2160
APPLICATION_SECONDS = BASE_APPLICATION_SECONDS + 2 * (
    SHOWCASE_SECONDS + PROTOCOL_SECONDS + SURFACE_SECONDS
)
WORKER_IMAGES_SECONDS = 180
EXTERNAL_RESERVE_SECONDS = 300
NATIVE_STEP_SECONDS = APPLICATION_SECONDS + WORKER_IMAGES_SECONDS + EXTERNAL_RESERVE_SECONDS

# Original 30-second Job startup allowance and 15-second assertion margin stay.
GENERATION_JOB_SECONDS = (
    FIRST_SECONDS + EXISTING_SECONDS + RQ2_SECONDS + SHOWCASE_SECONDS + PROTOCOL_SECONDS + 30
)
GENERATION_ASSERT_SECONDS = GENERATION_JOB_SECONDS + 15
